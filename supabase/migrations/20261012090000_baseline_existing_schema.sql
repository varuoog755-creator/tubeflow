-- Baseline migration.
--
-- This project predates `supabase db push`. The 14 public tables (profiles,
-- workspaces, workspace_members, youtube_channels, trigger_rules, campaigns,
-- comment_logs, processed_comments, tracked_links, click_events, conversions,
-- competitors, notifications, usage_metering) were applied by hand through the
-- SQL editor, so the project had no `supabase_migrations` history at all.
--
-- This file deliberately performs no schema change and, importantly, must not
-- insert into supabase_migrations.schema_migrations itself. The CLI records
-- every applied migration in that table after it runs, so inserting here as
-- well fails with:
--
--   duplicate key value violates unique constraint "schema_migrations_pkey"
--   (SQLSTATE 23505)
--
-- Existing tables are deliberately not re-created. Their DDL lives in the
-- legacy reference files src/lib/db-schema.sql and supabase_schema.sql, and
-- every statement in the migrations that follow is idempotent.
--
-- Nothing to execute. This file only marks where migration history begins.